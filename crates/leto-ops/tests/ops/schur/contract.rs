//! The Schur contract checks shared by the tests: certified eigenvalue blocks,
//! reconstruction, and the structural contract of `Q` and `T`.

use super::super::a_posteriori::{self, BlockEigenvalue};
use leto::{Array2, Storage};
use leto_ops::{schur, RealScalar};

/// The eigenvalues of the returned `T̂` (`f64`, with their evaluation
/// error) and the a-posteriori radius `‖E‖₂` of `schur`'s factors of the
/// image `a` (`a_posteriori.rs`): each is an eigenvalue of `a − E`.
pub(super) fn certified_blocks<T: RealScalar>(
    a: &[f64],
    decomposition: &leto_ops::RealSchur<T>,
) -> (Vec<BlockEigenvalue>, f64) {
    let n = decomposition.q().shape()[0];
    let as_f64 =
        |m: Array2<T>| -> Vec<f64> { m.storage().as_slice().iter().map(|v| v.to_f64()).collect() };
    let (q, t) = (as_f64(decomposition.q()), as_f64(decomposition.t()));
    let residual = a_posteriori::residual(a, &q, &t, &q, n, n, n);
    let radius = a_posteriori::schur_certificate(residual, a_posteriori::gram_defect(&q, n, n), &t);
    (a_posteriori::quasi_triangular_eigenvalues(&t, n), radius)
}

pub(super) fn mat(n: usize, data: Vec<f64>) -> Array2<f64> {
    Array2::from_shape_vec([n, n], data).unwrap()
}

/// `Q T Qᵀ` reconstructed by nested loops.
pub(super) fn reconstruct(q: &[f64], t: &[f64], n: usize) -> Vec<f64> {
    let mut qt = vec![0.0; n * n];
    for i in 0..n {
        for j in 0..n {
            let mut s = 0.0;
            for k in 0..n {
                s += q[i * n + k] * t[k * n + j];
            }
            qt[i * n + j] = s;
        }
    }
    let mut a = vec![0.0; n * n];
    for i in 0..n {
        for j in 0..n {
            let mut s = 0.0;
            for k in 0..n {
                s += qt[i * n + k] * q[j * n + k]; // (Qᵀ)[k,j] = Q[j,k]
            }
            a[i * n + j] = s;
        }
    }
    a
}

#[track_caller]
pub(super) fn assert_schur_contract(a: &Array2<f64>, n: usize) {
    let s = schur(&a.view()).unwrap();
    let q = s.q();
    let t = s.t();
    let qs = q.storage().as_slice();
    let ts = t.storage().as_slice();
    let asl = a.storage().as_slice();

    // 1. Reconstruction A = Q T Qᵀ.
    let recon = reconstruct(qs, ts, n);
    for (r, expected) in recon.iter().zip(asl.iter()) {
        assert!(
            (r - expected).abs() <= 1e-9,
            "reconstruction {r} vs {expected}"
        );
    }

    // 2. Q orthogonal: QᵀQ = I.
    for i in 0..n {
        for j in 0..n {
            let mut acc = 0.0;
            for k in 0..n {
                acc += qs[k * n + i] * qs[k * n + j];
            }
            let expected = if i == j { 1.0 } else { 0.0 };
            assert!((acc - expected).abs() <= 1e-9, "QᵀQ[{i},{j}] = {acc}");
        }
    }

    // 3. Quasi-upper-triangular: zero below the first subdiagonal, and any
    //    nonzero subdiagonal belongs to a 2×2 block with complex eigenvalues.
    for i in 0..n {
        for j in 0..n {
            if i > j + 1 {
                assert!(ts[i * n + j].abs() <= 1e-9, "T[{i},{j}] below subdiagonal");
            }
        }
    }
    let mut i = 0;
    while i < n {
        let block = i + 1 < n && ts[(i + 1) * n + i].abs() > 1e-9;
        if block {
            let aa = ts[i * n + i];
            let bb = ts[i * n + i + 1];
            let cc = ts[(i + 1) * n + i];
            let dd = ts[(i + 1) * n + i + 1];
            let disc = (aa - dd) * (aa - dd) + 4.0 * bb * cc;
            assert!(
                disc < 1e-12,
                "2x2 block must hold a complex pair (disc={disc})"
            );
            i += 2;
        } else {
            i += 1;
        }
    }
}
